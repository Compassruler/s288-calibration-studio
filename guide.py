def show_guide(root):
    """Open once and reuse the modeless help window; never send device commands."""
    previous = getattr(root, "_usage_guide", None)
    if previous is not None and previous.winfo_exists():
        previous.deiconify()
        previous.lift()
        previous.focus_set()
        return previous

    from ui import FeedbackButton, theme_widget

    window = tk.Toplevel(root)
    root._usage_guide = window
    window.title("S288 Studio · 使用指引")
    width = min(1080, root.winfo_screenwidth()-80)
    height = min(760, root.winfo_screenheight()-100)
    window.geometry(f"{width}x{height}")
    window.minsize(min(860, width), min(620, height))
    theme_widget(window, background="bg")
    window.transient(root)
    window.protocol("WM_DELETE_WINDOW", window.withdraw)
    window.bind("<Escape>", lambda _: window.withdraw())
    window.columnconfigure(1, weight=1)
    window.rowconfigure(1, weight=1)

    heading = ttk.Frame(window, padding=(20, 18, 20, 12))
    heading.grid(row=0, column=0, columnspan=2, sticky="we")
    ttk.Label(heading, text="使用指引", font=("Microsoft YaHei UI", 20, "bold")).pack(anchor="w")
    theme_widget(ttk.Label(heading, text="先模拟熟悉，再逐台标定。这里的操作只翻阅说明，不会控制舵机。"),
                 foreground="muted").pack(anchor="w", pady=(5, 0))

    navigation = ttk.Treeview(window, show="tree", selectmode="browse", height=7,
                              style="Sidebar.Treeview")
    navigation.column("#0", width=205, stretch=False)
    navigation.grid(row=1, column=0, sticky="ns", padx=(20, 12), pady=(0, 12))
    for index, (label, _, _) in enumerate(SECTIONS):
        navigation.insert("", "end", iid=str(index), text=label)

    content = ttk.Frame(window, style="Plain.TFrame")
    content.grid(row=1, column=1, sticky="nsew", padx=(0, 20), pady=(0, 12))
    content.columnconfigure(0, weight=1)
    content.rowconfigure(0, weight=1)
    text = tk.Text(content, wrap="word", width=1, height=1,
                   font=("Microsoft YaHei UI", 11), spacing1=3, spacing3=7,
                   padx=18, pady=14, relief="flat", highlightthickness=0)
    theme_widget(text, background="surface", foreground="ink", insertbackground="ink",
                 selectbackground="accent", selectforeground="accent_ink",
                 tags={"title": {"foreground": "accent"}})
    text.grid(row=0, column=0, sticky="nsew")
    text.tag_configure("title", font=("Microsoft YaHei UI", 16, "bold"),
                       spacing3=14)
    scrollbar = ttk.Scrollbar(content, orient="vertical", command=text.yview)
    scrollbar.grid(row=0, column=1, sticky="ns")
    text.configure(yscrollcommand=scrollbar.set, state="disabled")

    footer = ttk.Frame(window, padding=(20, 0, 20, 16))
    footer.grid(row=2, column=0, columnspan=2, sticky="we")
    page = tk.StringVar()
    theme_widget(ttk.Label(footer, textvariable=page), foreground="muted").pack(side="left")

    def select(index):
        navigation.selection_set(str(index))
        navigation.see(str(index))

    def move(delta):
        current = int(navigation.selection()[0])
        select(max(0, min(len(SECTIONS)-1, current+delta)))

    back = FeedbackButton(footer, text="上一节", style="Page.Quiet.TButton", command=lambda: move(-1))
    next_button = FeedbackButton(footer, text="下一节", style="Page.Soft.TButton", command=lambda: move(1))
    FeedbackButton(footer, text="返回工作台", style="Page.Primary.TButton", command=window.withdraw).pack(side="right")
    next_button.pack(side="right", padx=(6, 12))
    back.pack(side="right")

    def display(_=None):
        selected = navigation.selection()
        if not selected:
            return
        index = int(selected[0])
        _, title, body = SECTIONS[index]
        text.configure(state="normal")
        text.delete("1.0", "end")
        text.insert("end", title+"\n", "title")
        text.insert("end", body.strip()+"\n")
        text.configure(state="disabled")
        text.yview_moveto(0)
        page.set(f"第 {index+1} / {len(SECTIONS)} 节 · 可滚动阅读 · Esc 返回")
        back.configure(state="disabled" if index == 0 else "normal")
        next_button.configure(state="disabled" if index == len(SECTIONS)-1 else "normal")

    navigation.bind("<<TreeviewSelect>>", display)
    select(0)
    display()
    return window
